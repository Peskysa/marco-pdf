import { chromium } from 'playwright';
import { PDFDocument } from 'pdf-lib';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const folder = new URL('../../test-output/', import.meta.url);
await mkdir(folder, { recursive: true });
const sample = await PDFDocument.create();
for (let i = 1; i <= 3; i++) sample.addPage().drawText(`Marco PDF document page ${i}`, { x: 50, y: 700, size: 24 });
await writeFile(new URL('browser.pdf', folder), await sample.save());
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 1000 }, acceptDownloads: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', event => { if (event.type() === 'error') console.log('Browser:', event.text()); });
  page.on('requestfailed', request => console.log('Request failed:', request.url(), request.failure()));
  await page.goto(process.env.APP_URL || 'http://127.0.0.1:5173/');
  await page.screenshot({ path: new URL('web-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  await page.setInputFiles('#file', new URL('browser.pdf', folder).pathname.replace(/^\/(\w:)/, '$1'));
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('Documento abierto'));
  await page.click('#next');
  await page.waitForFunction(() => document.getElementById('page').value === '2');
  await page.click('#toggle-text');
  assert.ok((await page.textContent('#text')).includes('page 2'));
  await page.fill('#query', 'page 3'); await page.click('#find');
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('página 3'));
  await page.click('#split');
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('3 archivos'));
  const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#files button').nth(1).click()]);
  await download.saveAs(new URL('download.pdf', folder).pathname.replace(/^\/(\w:)/, '$1'));
  await page.selectOption('#mode', 'size'); await page.fill('#amount', '.00001'); await page.click('#split');
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('supera el límite'));
  // Create a scan from an actual browser raster, then run the bundled OCR engine.
  const raster = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 1600; canvas.height = 1200;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#fff'; ctx.fillRect(0, 0, 1600, 1200);
    ctx.fillStyle = '#000'; ctx.font = '60px Arial'; ctx.fillText('Marco PDF scanned document', 80, 150);
    ctx.fillText('Texto para reconocimiento OCR', 80, 270);
    return canvas.toDataURL('image/png');
  });
  const scan = await PDFDocument.create(); const image = await scan.embedPng(raster);
  scan.addPage([800, 600]).drawImage(image, { x: 0, y: 0, width: 800, height: 600 });
  await writeFile(new URL('browser-scan.pdf', folder), await scan.save());
  await page.setInputFiles('#file', new URL('browser-scan.pdf', folder).pathname.replace(/^\/(\w:)/, '$1'));
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('Documento abierto'));
  await page.click('#ocr');
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('PDF con texto listo'), { timeout: 120000 });
  const [ocr] = await Promise.all([page.waitForEvent('download'), page.locator('#files button').click()]);
  const recognized = new URL('browser-ocr.pdf', folder).pathname.replace(/^\/(\w:)/, '$1');
  await ocr.saveAs(recognized);
  await page.setInputFiles('#file', recognized);
  await page.waitForFunction(() => document.getElementById('status').textContent.includes('Documento abierto'));
  if (await page.locator('#text').isHidden()) await page.click('#toggle-text');
  assert.ok((await page.textContent('#text')).includes('Marco PDF'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.click('#fit');
  await page.screenshot({ path: new URL('web-mobile.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual(errors, []);
  console.log('Navegador OK: lectura, búsqueda, división, descarga, límite de MB, OCR real y móvil.');
} finally { await browser.close(); }
